export VICTORY_CARD_REHASH_RUNS=1
export VICTORY_JOIN_COPIES=1
export VICTORY_INDIRECT_WINDOW=1
export VICTORY_RELAY_COPY=1
export VICTORY_CARD_STEPS="${VICTORY_CARD_STEPS:-1}"
