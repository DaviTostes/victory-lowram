export VICTORY_UPLOAD_BAR=1
export VICTORY_BAR_ROOM_PERCENT="${VICTORY_BAR_ROOM_PERCENT:-82}"
export VICTORY_MEMORY_CARD_MB="${VICTORY_MEMORY_CARD_MB:-1536}"
export VICTORY_CARD_BUFFERS_MIN_KB=64
export VICTORY_CARD_BUFFERS_MB="${VICTORY_CARD_BUFFERS_MB:-3072}"
export VICTORY_CARD_ROOM_FOR_BUFFERS=1
export VICTORY_CARD_ROOM_FOR_TARGETS_MB="${VICTORY_CARD_ROOM_FOR_TARGETS_MB:-1200}"
export VICTORY_TEXTURE_ROOM_PERCENT="${VICTORY_TEXTURE_ROOM_PERCENT:-85}"
export VICTORY_PIPELINE_WAIT_MS="${VICTORY_PIPELINE_WAIT_MS:-500}"
export VICTORY_PIPELINE_BOOK="${VICTORY_PIPELINE_BOOK:-1}"

