# Op-lite/victory-scarlett freeze + streaming + CPU draw-setup package
export VICTORY_SOFT_VIEWS="${VICTORY_SOFT_VIEWS:-copies}"
export VICTORY_MAP_LOCK_FINE="${VICTORY_MAP_LOCK_FINE:-1}"
export VICTORY_TABLE_MEMO="${VICTORY_TABLE_MEMO:-1}"
export VICTORY_LIST_HOLD="${VICTORY_LIST_HOLD:-1}"
export VICTORY_LIST_ALIAS_EXACT="${VICTORY_LIST_ALIAS_EXACT:-1}"
export VICTORY_PARTIAL_DELTA="${VICTORY_PARTIAL_DELTA:-1}"
export VICTORY_SAMPLERS_MADE="${VICTORY_SAMPLERS_MADE:-0}"
export VICTORY_CARD_LISTS="${VICTORY_CARD_LISTS:-1}"
