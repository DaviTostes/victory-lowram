# Fast submission, relay, and texture upload pipeline
export VICTORY_TEXTURE_NO_WAIT=1
export VICTORY_RELAY="${VICTORY_RELAY:-2}"
export VICTORY_ASYNC_SUBMIT="${VICTORY_ASYNC_SUBMIT:-0}"
export VICTORY_WIDE_MERGE="${VICTORY_WIDE_MERGE:-0}"
